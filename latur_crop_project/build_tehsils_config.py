"""
Reads geocoded_tehsils.json (produced by geocode_tehsils.py) and writes
the TEHSILS_BY_DISTRICT structure into config.py, replacing the old
single-district DISTRICT / TEHSILS variables.

Run AFTER geocode_tehsils.py has finished (ideally with 0 rows left in
geocode_failures.csv - or with those filled in by hand and merged in):

    python build_tehsils_config.py

This edits config.py in place. It makes a config.py.bak backup first.
"""
import json
import csv
import shutil
from collections import defaultdict

GEOCODED_FILE = "geocoded_tehsils.json"
FAILURES_FILE = "geocode_failures.csv"
CONFIG_FILE = "config.py"

START_MARKER = "# --- Region setup"
END_MARKER = "# --- Crop list"


def load_manual_failures():
    """
    Picks up any manually-filled-in coordinates from geocode_failures.csv
    (only rows where you've actually typed in latitude/longitude).
    """
    manual = []
    try:
        with open(FAILURES_FILE, newline="", encoding="utf-8") as f:
            reader = csv.DictReader(f)
            for row in reader:
                if row.get("latitude") and row.get("longitude"):
                    manual.append({
                        "state": row["state"],
                        "division": row["division"],
                        "district": row["district"],
                        "tehsil": row["tehsil"],
                        "latitude": float(row["latitude"]),
                        "longitude": float(row["longitude"]),
                        "match_type": "manual",
                    })
    except FileNotFoundError:
        pass
    return manual


def build_structure(records):
    by_district = defaultdict(lambda: {"division": None, "tehsils": []})
    for r in records:
        entry = by_district[r["district"]]
        entry["division"] = r["division"]
        entry["tehsils"].append({
            "name": r["tehsil"],
            "latitude": round(r["latitude"], 4),
            "longitude": round(r["longitude"], 4),
        })
    # sort districts and tehsils for a stable, readable diff
    return dict(sorted(
        (d, {"division": v["division"],
             "tehsils": sorted(v["tehsils"], key=lambda t: t["name"])})
        for d, v in by_district.items()
    ))


def render_python(by_district):
    lines = []
    lines.append("# --- Region setup ---------------------------------------------------------")
    lines.append("# Auto-generated by build_tehsils_config.py from geocode_tehsils.py output.")
    lines.append("# Re-run both scripts if the tehsil list or coordinates need updating -")
    lines.append("# don't hand-edit coordinates here, fix them in geocoded_tehsils.json instead.")
    lines.append("STATE = \"Maharashtra\"")
    lines.append("")
    lines.append("TEHSILS_BY_DISTRICT = {")
    for district, info in by_district.items():
        lines.append(f'    "{district}": {{')
        lines.append(f'        "division": "{info["division"]}",')
        lines.append('        "tehsils": [')
        for t in info["tehsils"]:
            lines.append(
                f'            {{"name": "{t["name"]}", '
                f'"latitude": {t["latitude"]}, "longitude": {t["longitude"]}}},'
            )
        lines.append("        ],")
        lines.append("    },")
    lines.append("}")
    lines.append("")
    return "\n".join(lines) + "\n\n"


def main():
    try:
        with open(GEOCODED_FILE, encoding="utf-8") as f:
            records = json.load(f)
    except FileNotFoundError:
        print(f"ERROR: {GEOCODED_FILE} not found. Run geocode_tehsils.py first.")
        return

    manual = load_manual_failures()
    if manual:
        print(f"Merging in {len(manual)} manually-geocoded tehsil(s) from {FAILURES_FILE}")
        records = records + manual

    n_districts = len({r["district"] for r in records})
    print(f"Loaded {len(records)} geocoded tehsils across {n_districts} districts.")

    try:
        with open(FAILURES_FILE, newline="", encoding="utf-8") as f:
            reader = csv.DictReader(f)
            still_missing = [row for row in reader if not row.get("latitude")]
        if still_missing:
            print(f"WARNING: {len(still_missing)} tehsils still have no coordinates "
                  f"in {FAILURES_FILE} and will be MISSING from config.py. "
                  f"Fill them in and re-run this script if you want full coverage.")
    except FileNotFoundError:
        pass

    by_district = build_structure(records)
    new_block = render_python(by_district)

    with open(CONFIG_FILE, encoding="utf-8") as f:
        content = f.read()

    start = content.find(START_MARKER)
    end = content.find(END_MARKER)
    if start == -1 or end == -1:
        print(f"ERROR: couldn't find the region-setup markers in {CONFIG_FILE}. "
              f"Paste the generated block in manually - see config_tehsils_block.py.txt")
        with open("config_tehsils_block.py.txt", "w", encoding="utf-8") as f:
            f.write(new_block)
        return

    shutil.copy(CONFIG_FILE, CONFIG_FILE + ".bak")
    new_content = content[:start] + new_block + content[end:]
    with open(CONFIG_FILE, "w", encoding="utf-8") as f:
        f.write(new_content)

    print(f"config.py updated ({n_districts} districts, {len(records)} tehsils).")
    print(f"Backup of the old config.py saved as {CONFIG_FILE}.bak")
    print("\nNOTE: init_db.py, fetch_weather.py, fetch_soil.py, score_crops.py, and "
          "app.py still reference the old DISTRICT / TEHSILS variables and need to "
          "be updated to loop over TEHSILS_BY_DISTRICT instead - that's the next step.")


if __name__ == "__main__":
    main()
